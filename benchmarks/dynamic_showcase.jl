# Final milestone: the racing-showcase configurations, benchmarked.
#
#     julia --project=. benchmarks/dynamic_showcase.jl [n_cycles] [reps]
#
# Writes benchmarks/results/dynamic_showcase.md.
#
# Configurations (examples/showcase/common.jl, unchanged): quarter_track(), N = 10,
# dt = 0.1 s, NMPC objective weights, the shared initial condition (rear axle at s = 0,
# 1.0 m/s), no wall-clock budget (work per cycle bounded by count; see examples/showcase/README.md).
#   race · dynamic        DynamicNMPCController, no obstacle
#   obstacles · dynamic   DynamicNMPCController, the six-obstacle layout
#   race · kinematic      NMPCController (Cartesian-endpoint), no obstacle
#
# Measurement:
# - Compilation (controller construction and the first solve) is timed separately, in the
#   first repetition of each configuration only, when it is still uncompiled.
# - Warm-up: run_showcase runs discarded closed loops of the same configuration before the
#   recorded run.
# - Every recorded cycle counts; nothing is discarded or filtered.
# - Repetitions run in one process, one configuration after another; the machine's speed
#   state is not controlled.

include(joinpath(@__DIR__, "..", "examples", "showcase", "common.jl"))

const N_CYCLES = length(ARGS) >= 1 ? parse(Int, ARGS[1]) : 250
const REPS = length(ARGS) >= 2 ? parse(Int, ARGS[2]) : 3

const CONFIGS = [("race · dynamic", :dynamic, CircleObstacle[]), ("obstacles · dynamic", :dynamic, showcase_obstacles()),
    ("race · kinematic", :kinematic, CircleObstacle[])]

isempty(check_layout(showcase_obstacles())) || error("obstacle layout check failed")

rows = String[]
compile = String[]
for (name, model, obs) in CONFIGS
    for rep in 1:REPS
        run = run_showcase(model, obs, N_CYCLES)
        st = run_statistics(run)
        print_report("$name, run $rep", st)
        rep == 1 && push!(compile, @sprintf("| %s | %.1f | %.1f |", name, run.compile.construction, run.compile.first_solve))
        push!(rows, @sprintf("| %s | %d | %s | %d/%d | %.2f | %.1f | %.1f | %.1f | %.1f | %d / %d | %.2f | %s | %s |",
            name, rep, st.status, st.accepted, st.cycles, st.laps, st.median_ms, st.p95_ms, st.max_ms, st.within_100_pct,
            round(Int, st.iterations_median), st.iterations_max, st.solves_mean, @sprintf("%.4f", st.min_track_clearance),
            st.obstacles == 0 ? "–" : @sprintf("%.4f / %.4f / %d / %d", st.min_contact_clearance, st.min_buffer_clearance, st.collisions,
                st.buffer_intrusion_samples)))
    end
end

out = joinpath(@__DIR__, "results", "dynamic_showcase.md")
open(out, "w") do io
    println(io, "# Racing-showcase configurations (final milestone)\n")
    println(io, "Generated by `benchmarks/dynamic_showcase.jl` ($N_CYCLES cycles, $REPS runs per configuration), Julia $(VERSION), ",
        "commit `$(git_commit())`, $(Sys.CPU_NAME), $(Sys.CPU_THREADS) threads. See the script header for the measurement protocol.\n")
    println(io, "## Compilation (first repetition, before warm-up) [s]\n")
    println(io, "| configuration | construction | first solve |\n|:--|--:|--:|")
    foreach(r -> println(io, r), compile)
    println(io, "\nOnly the first configuration starts cold. Later configurations reuse code compiled in the same process ",
        "(JuMP, Ipopt and, for the second, the dynamic NMPC), so their times are lower bounds of a cold start.")
    println(io, "\n## Recorded runs (all cycles)\n")
    println(io, "Obstacle column: minimum clearance above contact [m] / above the required separation `D` [m] (negative = buffer ",
        "intrusion) / samples in contact / samples inside `D`, from the 10 ms plant trajectory.\n")
    println(io, "| configuration | run | status | accepted | laps | median [ms] | p95 [ms] | max [ms] | ≤ 100 ms [%] | Ipopt it. median / max | NLP solves / cycle | min. track clearance [m] | obstacles |")
    println(io, "|:--|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|")
    foreach(r -> println(io, r), rows)
    println(io, "\nThe cycle time is the whole `solve!` call (projection, guesses, NLP solves, validation). It is wall-clock time ",
        "on a laptop whose speed varies by about 2.5× between runs; it is not a real-time claim.")
end
println("wrote ", out)
